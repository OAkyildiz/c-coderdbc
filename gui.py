# ── Generation helpers ─────────────────────────────────────────────────────────

def _strip_section(text: str, section_comment: str) -> str:
    """Remove a ``/* {section_comment} */`` block and its content.

    Each section in the cantools-generated header consists of a comment line
    followed by one or more ``#define`` lines and a blank-line separator.
    The entire block (comment + defines + trailing blank line) is replaced
    with a single blank line so surrounding sections remain readable.

    This relies on the fixed structure of ``cantools.database.can.c_source``
    HEADER_FMT where every section ends with exactly one blank line.
    """
    pattern = rf'/\* {re.escape(section_comment)} \*/\n(?:[^\n]+\n)*\n'
    return re.sub(pattern, '\n', text)


def _strip_validate_funcs(text: str) -> str:
    """Remove ``_is_in_range`` / ``_is_in_phys_range`` from header or source.

    **Header** pattern — a doxygen block immediately before a ``bool``
    declaration (as generated by cantools ``SIGNAL_DECLARATION_IS_IN_RANGE_FMT``
    and ``SIGNAL_DECLARATION_IS_IN_PHYS_RANGE_FMT``)::

        /**
         * Check that given signal is in allowed range.
         * ...
         */
        bool db_msg_sig_is_in_range(int16_t value);

    **Source** pattern — a bare function definition whose body contains at most
    one level of nested braces (the cantools-generated bodies are always a
    single ``return (expr);`` statement with no nested ``{}``)::

        bool db_msg_sig_is_in_range(int16_t value)
        {
            return ((value >= 0) && (value <= 100));
        }
    """
    # Header: doxygen comment block + bool declaration
    text = re.sub(
        r'/\*\*\n(?:\s*\*[^\n]*\n)*\s*\*/\nbool [^\n]+_is_in(?:_phys)?_range[^\n]+;\n',
        '',
        text,
    )
    # Source: function definition; allow one level of nested braces in the body
    # (cantools generates simple single-expression bodies, but be defensive)
    text = re.sub(
        r'bool [^\n]+_is_in(?:_phys)?_range[^\n]+\n\{(?:[^{}]|\{[^{}]*\})*\}\n',
        '',
        text,
    )
    return text


def _replace_identifier_prefix(
    header: str, source: str, drv_name: str, new_prefix: str
) -> Tuple[str, str]:
    """Replace (or strip) the cantools database-name identifier prefix.

    cantools prefixes every generated symbol with ``database_name``.  This
    function replaces that prefix with *new_prefix* in all identifiers of the
    generated header and source, then restores the include guard (which must
    stay derived from the output file name, not from the identifier prefix).

    *new_prefix* = ``""`` strips the prefix entirely so symbols become
    ``msgname_pack`` instead of ``dbname_msgname_pack``.
    """
    from_lower = re.escape(drv_name.lower()) + "_"
    from_upper = re.escape(drv_name.upper()) + "_"
    to_lower = (new_prefix.lower() + "_") if new_prefix else ""
    to_upper = (new_prefix.upper() + "_") if new_prefix else ""

    # Negative lookbehind: only replace at the start of an identifier token.
    pat_lower = r"(?<![a-zA-Z0-9_])" + from_lower
    pat_upper = r"(?<![a-zA-Z0-9_])" + from_upper

    for pat, repl in [(pat_upper, to_upper), (pat_lower, to_lower)]:
        header = re.sub(pat, repl, header)
        source = re.sub(pat, repl, source)

    # Restore the include guard.  cantools built it as
    # f'{database_name.upper()}_H'; after our replacement it is
    # f'{to_upper}H' (e.g. '' + 'H' = 'H' when prefix is blank).
    # We always want the guard to reflect the output file name (drv_name.h).
    orig_guard = drv_name.upper() + "_H"
    new_guard = to_upper + "H"
    if new_guard != orig_guard:
        header = header.replace(f"#ifndef {new_guard}\n", f"#ifndef {orig_guard}\n", 1)
        header = header.replace(f"#define {new_guard}\n", f"#define {orig_guard}\n", 1)
        header = header.replace(f"/* {new_guard} */",     f"/* {orig_guard} */")

    return header, source


# ── Auto-grouping ──────────────────────────────────────────────────────────────

def detect_groups(
    messages: List["cantools.database.Message"],
    min_size: int = GROUP_MIN_SIZE,
) -> Dict[str, List["cantools.database.Message"]]:
    """
    Detect groups of similarly-named messages.

    Messages whose names match ``<prefix><digits>`` (with an optional
    trailing underscore before the digits) are placed in a group named
    ``<prefix>``.  Groups with fewer than *min_size* members are kept as
    individual entries.

    Returns a plain dict: ``group_name → [Message, …]``.
    """
    _NUM_SUFFIX = re.compile(r"^(.*?)_?(\d+)$")
    bucket: Dict[str, List] = defaultdict(list)

    for msg in messages:
        m = _NUM_SUFFIX.match(msg.name)
        if m:
            prefix = m.group(1).rstrip("_") or msg.name
            bucket[prefix].append(msg)
        else:
            bucket[msg.name].append(msg)

    groups: Dict[str, List] = {}
    for prefix, msgs in bucket.items():
        if len(msgs) >= min_size:
            groups[prefix] = sorted(msgs, key=lambda x: x.frame_id)
        else:
            for msg in msgs:
                groups[msg.name] = [msg]

    return groups


