    def _update_summary(self) -> None:
        total = len(self._messages)
        sel = sum(1 for m in self._messages if m.name in self._selected)
        func_sets = sum(
            1 for msgs in self._groups.values()
            if any(m.name in self._selected for m in msgs)
        )
        self._summary_var.set(f"{total} messages  |  {sel} selected")
        self._sel_summary.set(
            f"{sel} / {total} messages selected  →  {func_sets} function set(s) will be generated"
        )

    # ── Code generation ───────────────────────────────────────────────────────

    def _generate(self) -> None:
        if not self._messages:
            messagebox.showwarning("No DBC", "Please load a DBC file first.")
            return

        # For each group, emit only ONE representative message (the first selected
        # member).  This is the whole point of grouping: 111 radar frames with
        # identical signal layouts produce ONE pack/unpack function set, not 111.
        # Ungrouped (single-message) entries behave exactly as before.
        representatives: List["cantools.database.can.Message"] = []
        for msgs in sorted(self._groups.values(), key=lambda v: min(m.frame_id for m in v)):
            rep = next((m for m in msgs if m.name in self._selected), None)
            if rep is not None:
                representatives.append(rep)

        if not representatives:
            messagebox.showwarning(
                "Nothing Selected",
                "Select at least one message to generate code for.",
            )
            return

        out_dir = self._out_path.get().strip()
        drv_name = self._drv_name.get().strip()
        sym_prefix = self._sym_prefix.get().strip()

        if not out_dir:
            messagebox.showwarning("Missing", "Please specify an output directory.")
            return
        if not drv_name:
            messagebox.showwarning("Missing", "Please specify a driver name.")
            return

        # Check for file conflicts on the main thread, before starting the worker.
        out = Path(out_dir)
        h_name = f"{drv_name}.h"
        c_name = f"{drv_name}.c"
        conflicts = [f for f in (h_name, c_name) if (out / f).exists()]
        if conflicts:
            names = "\n  • ".join(conflicts)
            if not messagebox.askyesno(
                "Files Already Exist",
                f"The following file(s) already exist in:\n{out_dir}\n\n  • {names}\n\nOverwrite?",
                parent=self,
            ):
                return

        self._gen_btn.configure(state="disabled")
        self._progress.configure(bootstyle="success-striped", mode="indeterminate")
        self._progress.start(10)
        # Snapshot mutable state so the worker thread sees a consistent view.
        groups_snapshot = {k: list(v) for k, v in self._groups.items()}
        selected_snapshot = set(self._selected)
        threading.Thread(
            target=self._run_generation,
            args=(representatives, out_dir, drv_name, sym_prefix,
                  groups_snapshot, selected_snapshot),
            daemon=True,
        ).start()

    def _run_generation(
        self,
        selected: List["cantools.database.can.Message"],
        out_dir: str,
        drv_name: str,
        sym_prefix: str,
        groups: Dict[str, List["cantools.database.can.Message"]],
        selected_names: Set[str],
    ) -> None:
        try:
            # Build a filtered in-memory database from the selected messages.
            filtered_db = cantools.database.Database(messages=selected)
            h_name = f"{drv_name}.h"
            c_name = f"{drv_name}.c"
            node = self._node_name.get().strip() or None

            self._log(
                f"Generating C code for {len(selected)} function set(s)…", tag="info"
            )

            header, source, _, _ = _ct_generate(
                filtered_db,
                drv_name,
                h_name,
                c_name,
                f"{drv_name}_fuzzer.c",
                floating_point_numbers=self._opt_fp.get(),
                bit_fields=self._opt_bitfields.get(),
                use_float=self._opt_use_float.get(),
                node_name=node,
                use_round=self._opt_use_round.get(),
            )

            # Post-process: replace identifier prefix if the user specified one
            # different from the driver name (or blank = strip entirely).
            if sym_prefix != drv_name:
                header, source = _replace_identifier_prefix(
                    header, source, drv_name, sym_prefix
                )

            # Post-process: inject frame-ID macros for all selected grouped messages
            # before any section-strip passes (strips will then apply uniformly).
            if self._opt_expand_group_ids.get():
                header = _inject_group_frame_ids(
                    header, groups, selected_names, sym_prefix
                )

            # Post-process: strip disabled header sections
            if self._opt_skip_length.get():
                header = _strip_section(header, "Frame lengths in bytes.")
            if self._opt_skip_extended.get():
                header = _strip_section(header, "Extended or standard frame types.")
            if self._opt_skip_cycle_time.get():
                header = _strip_section(header, "Frame cycle times in milliseconds.")
            if self._opt_skip_frame_names.get():
                header = _strip_section(header, "Frame Names.")
            if self._opt_skip_sig_names.get():
                header = _strip_section(header, "Signal Names.")
            if self._opt_skip_choices.get():
                header = _strip_section(header, "Signal choices.")
            if self._opt_skip_validate.get():
                header = _strip_validate_funcs(header)
                source = _strip_validate_funcs(source)

            # Post-process: replace inline bitshift helpers with a user include.
            bitshift_hdr = self._bitshift_header.get().strip()
            if bitshift_hdr:
                source = _replace_bitshift_funcs(source, bitshift_hdr)

            # Write output files (any conflict was already confirmed in _generate)
            out = Path(out_dir)
            out.mkdir(parents=True, exist_ok=True)

            for fname, content in [(h_name, header), (c_name, source)]:
                fpath = out / fname
                fpath.write_text(content, encoding="utf-8")
                self._log(f"  Written: {fpath}", tag="info")

            self._log(
                f"✅  Generation complete!  Output → {out_dir}", tag="success"
            )

        except Exception as exc:
            import traceback
            self._log(f"❌  {exc}", tag="danger")
            self._log(traceback.format_exc(), tag="danger")
        finally:
            self.after(0, self._generation_done)

    def _generation_done(self) -> None:
        self._progress.stop()
        self._progress.configure(bootstyle="secondary", mode="determinate")
        self._progress["value"] = 0
        self._gen_btn.configure(state="normal")

