def _strip_section(text: str, section_comment: str) -> str:
    """Remove a ``/* {section_comment} */`` block and its content.

    Each section in the cantools-generated header consists of a comment line
    followed by one or more ``#define`` lines and a blank-line separator.
    The entire block (comment + defines + trailing blank line) is replaced
    with a single blank line so surrounding sections remain readable.

    The pattern handles sections that contain internal blank lines, such as
    the ``Signal choices.`` section when a message has multiple signals with
    choices (cantools emits a blank line between each signal's group of choice
    defines).  Matching stops at the opening ``/* `` of the next section so
    no unrelated content is consumed.
    """
    # Stop matching when the next line begins another /* comment */ section.
    pattern = rf'/\* {re.escape(section_comment)} \*/\n(?:(?!/\* ).*\n|\n)*'
    return re.sub(pattern, '\n', text)


def _strip_validate_funcs(text: str) -> str:
    """Remove ``_is_in_range`` / ``_is_in_phys_range`` from header or source.

    **Header** pattern — a doxygen block immediately before a ``bool``
    declaration (as generated by cantools ``SIGNAL_DECLARATION_IS_IN_RANGE_FMT``
    and ``SIGNAL_DECLARATION_IS_IN_PHYS_RANGE_FMT``)::

        /**
         * Check that given signal is in allowed range.
         * ...
         */
        bool db_msg_sig_is_in_range(int16_t value);

    **Source** pattern — a bare function definition whose body contains at most
    one level of nested braces (the cantools-generated bodies are always a
    single ``return (expr);`` statement with no nested ``{}``)::

        bool db_msg_sig_is_in_range(int16_t value)
        {
            return ((value >= 0) && (value <= 100));
        }
    """
    # Header: doxygen comment block + bool declaration
    text = re.sub(
        r'/\*\*\n(?:\s*\*[^\n]*\n)*\s*\*/\nbool [^\n]+_is_in(?:_phys)?_range[^\n]+;\n',
        '',
        text,
    )
    # Source: function definition; allow one level of nested braces in the body
    # (cantools generates simple single-expression bodies, but be defensive)
    text = re.sub(
        r'bool [^\n]+_is_in(?:_phys)?_range[^\n]+\n\{(?:[^{}]|\{[^{}]*\})*\}\n',
        '',
        text,
    )
    return text


def _common_suffix_ci(names: List[str]) -> str:
    """Return the longest common suffix shared by all *names* (case-insensitive)."""
    if not names:
        return ""
    lower = [n.lower() for n in names]
    ref = lower[0]
    for length in range(len(ref), 0, -1):
        candidate = ref[-length:]
        if all(n.endswith(candidate) for n in lower):
            return candidate
    return ""


def _strip_redundant_signal_suffixes(
    header: str,
    source: str,
    groups: Dict[str, List],
    selected_names: Set[str],
) -> Tuple[str, str]:
    """Remove redundant common suffix from signal identifiers in grouped-message output.

    When every signal in a representative grouped message shares the same
    trailing suffix (e.g. ``_Obj_00`` in a group of ``ARS_Obj_00`` …
    ``ARS_Obj_63``), cantools emits function names like
    ``ars_obj_00_dist_x_obj_00_encode``.  This post-pass strips the repeated
    suffix so the result is ``ars_obj_00_dist_x_encode``.

    The replacement targets only all-lowercase (function/variable/struct-member
    names) and all-uppercase (#define macro names) identifier tokens; mixed-case
    string literals and doxygen comments are left untouched.
    """
    for msgs in groups.values():
        if len(msgs) < 2:
            continue
        rep = next((m for m in msgs if m.name in selected_names), None)
        if rep is None or not rep.signals:
            continue

        # Build the C-identifier form of each signal name using the same
        # conversion cantools uses: camel_to_snake_case for lowercase identifiers
        # (function names, struct members) and camel_to_snake_case + upper for
        # #define macro names.
        sig_ids_lower = [_ct_snake(s.name) for s in rep.signals]
        sig_ids_upper = [_ct_snake(s.name).upper() for s in rep.signals]

        suffix_lower = _common_suffix_ci(sig_ids_lower)
        if not suffix_lower or not suffix_lower.startswith("_") or len(suffix_lower) < 2:
            continue
        suffix_upper = _common_suffix_ci(sig_ids_upper)
        if not suffix_upper or not suffix_upper.startswith("_"):
            continue

        # Verify stripping would not create duplicate or empty identifiers.
        strip_lo = len(suffix_lower)
        strip_up = len(suffix_upper)
        new_lower = [n[:-strip_lo] for n in sig_ids_lower]
        new_upper = [n[:-strip_up] for n in sig_ids_upper]
        if (not all(new_lower)
                or len(set(new_lower)) != len(new_lower)
                or not all(new_upper)):
            continue

        # Sort longest-first so a longer name is replaced before any shorter
        # name that shares a suffix with it, avoiding partial-match surprises.
        quads = sorted(
            zip(sig_ids_lower, new_lower, sig_ids_upper, new_upper),
            key=lambda t: len(t[0]),
            reverse=True,
        )
        for old_lo, new_lo, old_up, new_up in quads:
            header = header.replace(old_lo, new_lo).replace(old_up, new_up)
            source = source.replace(old_lo, new_lo).replace(old_up, new_up)

    return header, source


def _strip_grouped_message_name_prefix(
    header: str,
    source: str,
    groups: Dict[str, List],
    selected_names: Set[str],
) -> Tuple[str, str]:
    """Strip the snake_case message-name segment from grouped-message identifiers.

    After the identifier-prefix replacement step identifiers for a grouped
    representative message ``ARS_Obj_00`` look like::

        <pfx>_ars_obj_00_dist_x_encode       (function / struct-tag)
        <PFX>_ARS_OBJ_00_DIST_X_NAME         (#define macro)

    Since the grouping already captures the per-instance variation, the
    ``ars_obj_00`` / ``ARS_OBJ_00`` segment is redundant.  This pass removes
    it so the result uses only the sym_prefix::

        <pfx>_dist_x_encode
        <PFX>_DIST_X_NAME

    Only applied to genuine groups (2+ messages).  Mixed-case string literals
    (``"ARS_Obj_00"``) and doxygen comments are left untouched because they
    use the original capitalisation which neither pattern matches.
    """
    for msgs in groups.values():
        if len(msgs) < 2:
            continue
        rep = next((m for m in msgs if m.name in selected_names), None)
        if rep is None:
            continue

        msg_lower = _ct_snake(rep.name)   # e.g. "ars_obj_00"
        msg_upper = msg_lower.upper()     # e.g. "ARS_OBJ_00"

        # Strip "ars_obj_00_" and "ARS_OBJ_00_" from all identifiers.
        # String literals always use the original mixed case ("ARS_Obj_00")
        # so simple str.replace is both sufficient and safe here.
        header = header.replace(msg_lower + "_", "").replace(msg_upper + "_", "")
        source = source.replace(msg_lower + "_", "").replace(msg_upper + "_", "")

    return header, source


def _strip_message_name_prefix(
    header: str,
    source: str,
    groups: Dict[str, List],
    selected_names: Set[str],
    frame_id_prefix_items: Set[str],
) -> Tuple[str, str]:
    """Strip the message/group name prefix from all generated identifiers.

    This is the per-message generalisation of
    :func:`_strip_grouped_message_name_prefix`.  While that helper only acts on
    genuine multi-message groups, this function applies to **every** selected
    message or group — including single-message entries.

    After the earlier prefix-normalisation steps, each group or single message
    contributes identifiers of the form::

        <group_or_msg_name>_<signal_name>_encode
        <GROUP_OR_MSG_NAME>_<SIGNAL_NAME>_ENCODE_MAX

    This pass removes the leading ``<group_or_msg_name>_`` segment so only the
    signal-derived part remains::

        <signal_name>_encode
        <SIGNAL_NAME>_ENCODE_MAX

    Entries that already had the frame-ID prefix applied (i.e. their group key
    is in *frame_id_prefix_items*) are skipped — their prefix is already the
    hex frame ID, not the message name.

    Mixed-case string literals are unaffected because they use the original
    capitalisation, which does not match the all-lower / all-upper patterns.
    """
    for group_key, msgs in groups.items():
        if group_key in frame_id_prefix_items:
            continue  # fid prefix was already applied; leave those identifiers alone
        rep = next((m for m in msgs if m.name in selected_names), None)
        if rep is None:
            continue

        name_lower = _ct_snake(group_key)
        name_upper = name_lower.upper()

        header = header.replace(name_lower + "_", "").replace(name_upper + "_", "")
        source = source.replace(name_lower + "_", "").replace(name_upper + "_", "")

    return header, source


def _inject_group_frame_ids(
    header: str,
    groups: Dict[str, List],
    selected_names: Set[str],
    sym_prefix: str,
) -> str:
    """Inject per-message frame-ID macros for every selected message in a group.

    When code is generated for a group, cantools only emits macros for the
    representative (first selected) member.  This function appends the missing
    macros for the remaining selected members so every message ID and its
    companion constants are present in the header.
    """
    effective_prefix = (sym_prefix.upper() + "_") if sym_prefix else ""

    # Collect non-representative selected messages across all multi-message groups.
    extra_msgs = []
    for msgs in groups.values():
        if len(msgs) < 2:
            continue
        sel_msgs = [m for m in msgs if m.name in selected_names]
        if len(sel_msgs) < 2:
            continue
        extra_msgs.extend(sel_msgs[1:])  # first entry is the representative

    if not extra_msgs:
        return header

    pfx = effective_prefix

    def _append_to_section(text: str, comment: str, new_lines: List[str]) -> str:
        """Insert *new_lines* at the end of a ``/* comment */`` section."""
        if not new_lines:
            return text
        pattern = rf'(/\* {re.escape(comment)} \*/\n(?:[^\n]+\n)*)\n'
        def _repl(m: "re.Match") -> str:
            return m.group(1) + "\n".join(new_lines) + "\n\n"
        return re.sub(pattern, _repl, text, count=1)

    header = _append_to_section(
        header, "Frame ids.",
        [f"#define {pfx}{m.name.upper()}_FRAME_ID (0x{m.frame_id:x}u)" for m in extra_msgs],
    )
    header = _append_to_section(
        header, "Frame lengths in bytes.",
        [f"#define {pfx}{m.name.upper()}_LENGTH ({m.length}u)" for m in extra_msgs],
    )
    header = _append_to_section(
        header, "Extended or standard frame types.",
        [f"#define {pfx}{m.name.upper()}_IS_EXTENDED ({1 if m.is_extended_frame else 0})"
         for m in extra_msgs],
    )
    cyc_lines = [
        f"#define {pfx}{m.name.upper()}_CYCLE_TIME_MS ({int(m.cycle_time)}u)"
        for m in extra_msgs
        if getattr(m, "cycle_time", None) is not None
    ]
    header = _append_to_section(header, "Frame cycle times in milliseconds.", cyc_lines)
    header = _append_to_section(
        header, "Frame Names.",
        [f'#define {pfx}{m.name.upper()}_NAME "{m.name}"' for m in extra_msgs],
    )
    return header


def _inject_group_range_macros(
    header: str,
    groups: Dict[str, List],
    selected_names: Set[str],
) -> str:
    """Inject ``xxx_FRAME_ID_FIRST``, ``xxx_FRAME_ID_LAST``, and
    ``xxx_FRAME_ID_COUNT`` macros into the header for every genuine group.

    The macros are appended to the *Frame ids.* section so they sit right
    alongside the individual per-message ``_FRAME_ID`` macros.  Messages
    within a group are ordered by ascending frame ID.

    Example output for group key ``ARS_Obj`` (6 messages, IDs 0x400–0x405)::

        #define ARS_OBJ_FRAME_ID_FIRST (0x400u)
        #define ARS_OBJ_FRAME_ID_LAST  (0x405u)
        #define ARS_OBJ_FRAME_ID_COUNT (6u)
    """
    range_lines: List[str] = []

    for group_key, msgs in groups.items():
        if len(msgs) < 2:
            continue
        sel_msgs = [m for m in msgs if m.name in selected_names]
        if not sel_msgs:
            continue
        ids = sorted(m.frame_id for m in sel_msgs)
        group_upper = _ct_snake(group_key).upper()
        range_lines.extend([
            f"#define {group_upper}_FRAME_ID_FIRST (0x{ids[0]:x}u)",
            f"#define {group_upper}_FRAME_ID_LAST  (0x{ids[-1]:x}u)",
            f"#define {group_upper}_FRAME_ID_COUNT ({len(ids)}u)",
        ])

    if not range_lines:
        return header

    def _append_to_section(text: str, comment: str, new_lines: List[str]) -> str:
        if not new_lines:
            return text
        pattern = rf'(/\* {re.escape(comment)} \*/\n(?:[^\n]+\n)*)\n'
        def _repl(m: "re.Match") -> str:
            return m.group(1) + "\n".join(new_lines) + "\n\n"
        return re.sub(pattern, _repl, text, count=1)

    return _append_to_section(header, "Frame ids.", range_lines)


def _replace_bitshift_funcs(source: str, bitshift_header: str) -> str:
    """Replace the inline bitshift helper block with a user-supplied ``#include``.

    The generated ``.c`` file contains a block of ``static inline`` helper
    functions (``pack_left_shift_*``, ``pack_right_shift_*``,
    ``unpack_left_shift_*``, ``unpack_right_shift_*``) immediately after the
    ``#include "drvname.h"`` line.  When *bitshift_header* is non-empty, that
    entire block is removed and ``#include "<bitshift_header>"`` is inserted in
    its place.  Passing an empty string leaves the inline functions unchanged.
    """
    # Each helper matches: "static inline <type> <name>(<args>)\n{\n    return ...;\n}\n\n"
    # [^)]+ covers the (possibly multi-line) argument list; [^}]+ covers the body.
    pattern = r"(?:static inline \S+ \S+\([^)]+\)\n\{[^}]+\}\n\n)+"
    return re.sub(pattern, f'#include "{bitshift_header}"\n\n', source, count=1)


def _replace_identifier_prefix(
    header: str, source: str, drv_name: str, new_prefix: str
) -> Tuple[str, str]:
    """Replace (or strip) the cantools database-name identifier prefix.

    cantools prefixes every generated symbol with ``database_name``.  This
    function replaces that prefix with *new_prefix* in all identifiers of the
    generated header and source, then restores the include guard (which must
    stay derived from the output file name, not from the identifier prefix).

    *new_prefix* = ``""`` strips the prefix entirely so symbols become
    ``msgname_pack`` instead of ``dbname_msgname_pack``.
    """
    from_lower = re.escape(drv_name.lower()) + "_"
    from_upper = re.escape(drv_name.upper()) + "_"
    to_lower = (new_prefix.lower() + "_") if new_prefix else ""
    to_upper = (new_prefix.upper() + "_") if new_prefix else ""

    # Negative lookbehind: only replace at the start of an identifier token.
    pat_lower = r"(?<![a-zA-Z0-9_])" + from_lower
    pat_upper = r"(?<![a-zA-Z0-9_])" + from_upper

    for pat, repl in [(pat_upper, to_upper), (pat_lower, to_lower)]:
        header = re.sub(pat, repl, header)
        source = re.sub(pat, repl, source)

    # Restore the include guard.  cantools built it as
    # f'{database_name.upper()}_H'; after our replacement it is
    # f'{to_upper}H' (e.g. '' + 'H' = 'H' when prefix is blank).
    # We always want the guard to reflect the output file name (drv_name.h).
    orig_guard = drv_name.upper() + "_H"
    new_guard = to_upper + "H"
    if new_guard != orig_guard:
        header = header.replace(f"#ifndef {new_guard}\n", f"#ifndef {orig_guard}\n", 1)
        header = header.replace(f"#define {new_guard}\n", f"#define {orig_guard}\n", 1)
        header = header.replace(f"/* {new_guard} */",     f"/* {orig_guard} */")

    return header, source


def _rename_grouped_message_prefix(
    header: str,
    source: str,
    groups: Dict[str, List],
    selected_names: Set[str],
) -> Tuple[str, str]:
    """Rename the representative message's identifier prefix to the group key.

    After the drv-name strip, grouped messages still carry the representative
    message's snake-case name as a prefix::

        ars_obj_00_dist_x_encode       (group key: ARS_Obj, rep: ARS_Obj_00)

    This pass replaces the representative-message segment with the group key::

        ars_obj_dist_x_encode

    Only applied to genuine groups (2+ messages) where the group key's
    snake-case name differs from the representative's.  String literals
    like ``"ARS_Obj_00"`` are unaffected because they use the original
    mixed-case spelling, which does not match the all-lower / all-upper
    identifier patterns.
    """
    for group_key, msgs in groups.items():
        if len(msgs) < 2:
            continue
        rep = next((m for m in msgs if m.name in selected_names), None)
        if rep is None:
            continue

        msg_lower = _ct_snake(rep.name)     # e.g. "ars_obj_00"
        group_lower = _ct_snake(group_key)  # e.g. "ars_obj"

        if msg_lower == group_lower:
            continue  # representative name already matches group key

        msg_upper = msg_lower.upper()
        group_upper = group_lower.upper()

        # Replace identifier segments that carry the representative's name.
        # The trailing "_" avoids partial word matches.
        header = header.replace(msg_lower + "_", group_lower + "_")
        header = header.replace(msg_upper + "_", group_upper + "_")
        source = source.replace(msg_lower + "_", group_lower + "_")
        source = source.replace(msg_upper + "_", group_upper + "_")

    return header, source


def _apply_frame_id_prefix(
    header: str,
    source: str,
    groups: Dict[str, List],
    selected_names: Set[str],
    frame_id_prefix_items: Set[str],
) -> Tuple[str, str]:
    """Replace the group/message name prefix with a hex frame-ID prefix.

    For groups/messages whose key is in *frame_id_prefix_items*, replaces the
    group-key-derived identifier prefix with ``x{frame_id:x}_``.  For example,
    if group key ``ARS_Obj`` has representative frame ID ``0x400``, every
    identifier like ``ars_obj_dist_x_encode`` becomes ``x400_dist_x_encode``.

    This is useful when signal names don't share the frame-name prefix and the
    auto-grouped name would produce misleading identifiers.
    """
    for group_key, msgs in groups.items():
        if group_key not in frame_id_prefix_items:
            continue
        rep = next((m for m in msgs if m.name in selected_names), None)
        if rep is None:
            continue

        group_lower = _ct_snake(group_key)
        group_upper = group_lower.upper()
        fid_lower = f"x{rep.frame_id:x}"
        fid_upper = fid_lower.upper()

        header = header.replace(group_lower + "_", fid_lower + "_")
        header = header.replace(group_upper + "_", fid_upper + "_")
        source = source.replace(group_lower + "_", fid_lower + "_")
        source = source.replace(group_upper + "_", fid_upper + "_")

    return header, source


# ── Auto-grouping ──────────────────────────────────────────────────────────────

def detect_groups(
    messages: List["cantools.database.Message"],
    min_size: int = GROUP_MIN_SIZE,
) -> Dict[str, List["cantools.database.Message"]]:
    """
    Detect groups of similarly-named messages.

    Messages whose names end with a numeric suffix (``<prefix>_?<digits>``,
    e.g. ``ARS_Obj_00`` … ``ARS_Obj_105``) or a single-character alphabetic
    suffix after an underscore (``<prefix>_<letter>``, e.g. ``Name_k`` …
    ``Name_n``) are placed in a group named ``<prefix>``.  Groups with fewer
    than *min_size* members are kept as individual entries.

    Returns a plain dict: ``group_name → [Message, …]``.
    """
    _NUM_SUFFIX   = re.compile(r"^(.*?)_?(\d+)$")
    _ALPHA_SUFFIX = re.compile(r"^(.+?)_([a-zA-Z])$")
    bucket: Dict[str, List] = defaultdict(list)

    for msg in messages:
        m = _NUM_SUFFIX.match(msg.name)
        if m:
            prefix = m.group(1).rstrip("_") or msg.name
            bucket[prefix].append(msg)
        else:
            m = _ALPHA_SUFFIX.match(msg.name)
            if m:
                bucket[m.group(1)].append(msg)
            else:
                bucket[msg.name].append(msg)

    groups: Dict[str, List] = {}
    for prefix, msgs in bucket.items():
        if len(msgs) >= min_size:
            groups[prefix] = sorted(msgs, key=lambda x: x.frame_id)
        else:
            for msg in msgs:
                groups[msg.name] = [msg]

    return groups


