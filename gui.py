    # ── DBC loading ──────────────────────────────────────────────────────────

    def _browse_dbc(self) -> None:
        docs = Path.home() / "Documents"
        initial = str(docs) if docs.is_dir() else str(Path.home())
        path = filedialog.askopenfilename(
            title="Select DBC file",
            initialdir=initial,
            filetypes=[("DBC files", "*.dbc"), ("All files", "*.*")],
        )
        if path:
            self._dbc_path.set(path)
            self._load_dbc(path)

    def _load_dbc(self, path: str) -> None:
        self._log(f"Loading: {path}", tag="info")
        try:
            self._db = cantools.database.load_file(path)
        except Exception as exc:
            self._log(f"ERROR parsing DBC file: {exc}", tag="danger")
            return

        self._messages = sorted(self._db.messages, key=lambda m: m.frame_id)
        self._selected = {m.name for m in self._messages}

        # Start with a flat (one group per message) layout
        self._groups = {msg.name: [msg] for msg in self._messages}
        self._populate_tree()
        self._update_summary()
        self._log(f"Loaded {len(self._messages)} message(s).", tag="success")

        # Auto-fill driver name and output dir from the filename
        stem = Path(path).stem
        if not self._drv_name.get():
            self._drv_name.set(stem)
        if not self._out_path.get():
            self._out_path.set(str(Path(path).parent / "gencode"))

    # ── Tree population ───────────────────────────────────────────────────────

    def _populate_tree(self) -> None:
        """Rebuild the entire Treeview from *self._groups*, respecting the search filter."""
        self._tree.delete(*self._tree.get_children())
        self._tree_items.clear()

        filter_text = self._search_var.get().lower()

        for group_name, msgs in sorted(
            self._groups.items(), key=lambda kv: min(m.frame_id for m in kv[1])
        ):
            visible = [
                m for m in msgs
                if not filter_text or filter_text in m.name.lower()
            ]
            if not visible:
                continue

            is_group = len(msgs) > 1

            if is_group:
                all_sel = all(m.name in self._selected for m in visible)
                any_sel = any(m.name in self._selected for m in visible)
                chk = (
                    CHECKBOX_ON if all_sel
                    else CHECKBOX_PARTIAL if any_sel
                    else CHECKBOX_OFF
                )
                min_id = min(m.frame_id for m in visible)
                total_sigs = sum(len(m.signals) for m in visible)
                g_iid = f"group::{group_name}"
                self._tree.insert(
                    "", END, iid=g_iid,
                    text=f"0x{min_id:03X}+  {group_name}  ({len(visible)} frames → 1 function set)",
                    values=(chk, "", total_sigs, ""),
                    open=False,
                    tags=("group",),
                )
                self._tree_items[g_iid] = ("group", group_name)
                for msg in visible:
                    self._insert_message(g_iid, msg)
            else:
                self._insert_message("", msgs[0])

        self._tree.tag_configure("group",  font=("", 11, "bold"))
        self._tree.tag_configure("signal", foreground="#888888")
        self._refresh_heading()

    def _insert_message(self, parent_iid: str, msg: "cantools.database.can.Message") -> None:
        selected = msg.name in self._selected
        chk = CHECKBOX_ON if selected else CHECKBOX_OFF
        m_iid = f"msg::{msg.frame_id}"
        sender = msg.senders[0] if msg.senders else ""
        self._tree.insert(
            parent_iid, END, iid=m_iid,
            text=f"0x{msg.frame_id:03X}  {msg.name}",
            values=(chk, msg.length, len(msg.signals), sender),
            tags=("msg",),
        )
        self._tree_items[m_iid] = ("msg", msg)

        for sig in msg.signals:
            s_iid = f"sig::{msg.frame_id}::{sig.name}"
            bo = "LE" if sig.byte_order == "little_endian" else "BE"
            vt = "S" if sig.is_signed else "U"
            self._tree.insert(
                m_iid, END, iid=s_iid,
                text=f"    {sig.name}  [{sig.start}|{sig.length}]",
                values=("", bo, vt, ""),
                tags=("signal",),
            )

    # ── Tree interaction ──────────────────────────────────────────────────────

    def _on_tree_expand_collapse(self, event: "tk.Event[ttk.Treeview]") -> None:
        """Suppress the checkbox toggle for the ButtonRelease-1 that follows
        a native expand/collapse indicator click.

        Tkinter fires <<TreeviewOpen>> / <<TreeviewClose>> (generated inside
        the widget's class binding for Button-1) *before* ButtonRelease-1
        reaches our handler.  Setting this flag here is therefore enough to
        reliably block the unwanted toggle, regardless of theme or platform.
        """
        self._suppress_next_click = True

    def _on_tree_click(self, event: "tk.Event[ttk.Treeview]") -> None:
        """Toggle message/group selection when the user clicks the name column."""
        region = self._tree.identify_region(event.x, event.y)
        if region not in ("tree", "cell"):
            return

        iid = self._tree.identify_row(event.y)
        if not iid or iid not in self._tree_items:
            return

        # React to clicks in the tree/name column (#0) or the checkbox column (#1).
        if self._tree.identify_column(event.x) not in ("#0", "#1"):
            return

        # Ignore clicks caused by the native expand/collapse indicator (▶ / ▼).
        # _on_tree_expand_collapse sets this flag via <<TreeviewOpen/Close>>,
        # which always fires before ButtonRelease-1 reaches us.
        if self._suppress_next_click:
            self._suppress_next_click = False
            return

        kind, data = self._tree_items[iid]
        if kind == "group":
            self._toggle_group(str(data))
        elif kind == "msg":
            self._toggle_message(data)  # type: ignore[arg-type]

        self._update_summary()

    def _toggle_message(self, msg: "cantools.database.can.Message") -> None:
        if msg.name in self._selected:
            self._selected.discard(msg.name)
        else:
            self._selected.add(msg.name)
        selected = msg.name in self._selected
        chk = CHECKBOX_ON if selected else CHECKBOX_OFF
        m_iid = f"msg::{msg.frame_id}"
        if self._tree.exists(m_iid):
            self._tree.set(m_iid, "sel", chk)
        self._refresh_parent_group(msg)
        self._refresh_heading()

    def _toggle_group(self, group_name: str) -> None:
        msgs = self._groups[group_name]
        all_sel = all(m.name in self._selected for m in msgs)
        if all_sel:
            for msg in msgs:
                self._selected.discard(msg.name)
        else:
            for msg in msgs:
                self._selected.add(msg.name)
        for msg in msgs:
            chk = CHECKBOX_ON if msg.name in self._selected else CHECKBOX_OFF
            m_iid = f"msg::{msg.frame_id}"
            if self._tree.exists(m_iid):
                self._tree.set(m_iid, "sel", chk)
        self._refresh_group_item(group_name)
        self._refresh_heading()

    def _refresh_group_item(self, group_name: str) -> None:
        g_iid = f"group::{group_name}"
        if not self._tree.exists(g_iid):
            return
        msgs = self._groups[group_name]
        all_sel = all(m.name in self._selected for m in msgs)
        any_sel = any(m.name in self._selected for m in msgs)
        chk = (
            CHECKBOX_ON if all_sel
            else CHECKBOX_PARTIAL if any_sel
            else CHECKBOX_OFF
        )
        n = len(msgs)
        min_id = min(m.frame_id for m in msgs)
        self._tree.set(g_iid, "sel", chk)

    def _refresh_parent_group(self, msg: "cantools.database.can.Message") -> None:
        for group_name, msgs in self._groups.items():
            if msg in msgs and len(msgs) > 1:
                self._refresh_group_item(group_name)
                break

    # ── Grouping ──────────────────────────────────────────────────────────────

    def _auto_group(self) -> None:
        if not self._messages:
            return
        self._groups = detect_groups(self._messages)
        self._populate_tree()
        n_groups = sum(1 for v in self._groups.values() if len(v) > 1)
        self._log(
            f"Auto-grouping complete: {n_groups} group(s) detected.", tag="info"
        )

    def _ungroup(self) -> None:
        if not self._messages:
            return
        self._groups = {msg.name: [msg] for msg in self._messages}
        self._populate_tree()

    # ── Selection helpers ─────────────────────────────────────────────────────

    def _select_all(self) -> None:
        self._selected = {m.name for m in self._messages}
        self._populate_tree()
        self._update_summary()

    def _deselect_all(self) -> None:
        self._selected.clear()
        self._populate_tree()
        self._update_summary()

    def _toggle_all_heading(self) -> None:
        """Toggle all messages on/off when the sel column heading checkbox is clicked."""
        if not self._messages:
            return
        all_sel = all(m.name in self._selected for m in self._messages)
        if all_sel:
            self._selected.clear()
        else:
            self._selected = {m.name for m in self._messages}
        self._populate_tree()
        self._update_summary()

    def _refresh_heading(self) -> None:
        """Update the sel column heading checkbox to reflect the current selection state."""
        if not self._messages:
            chk = CHECKBOX_OFF
        elif all(m.name in self._selected for m in self._messages):
            chk = CHECKBOX_ON
        elif any(m.name in self._selected for m in self._messages):
            chk = CHECKBOX_PARTIAL
        else:
            chk = CHECKBOX_OFF
        self._tree.heading("sel", text=chk)

    def _apply_filter(self) -> None:
        self._populate_tree()

    def _update_summary(self) -> None:
        total = len(self._messages)
        sel = sum(1 for m in self._messages if m.name in self._selected)
        func_sets = sum(
            1 for msgs in self._groups.values()
            if any(m.name in self._selected for m in msgs)
        )
        self._summary_var.set(f"{total} messages  |  {sel} selected")
        self._sel_summary.set(
            f"{sel} / {total} messages selected  →  {func_sets} function set(s) will be generated"
        )

    # ── Code generation ───────────────────────────────────────────────────────

    def _generate(self) -> None:
        if not self._messages:
            messagebox.showwarning("No DBC", "Please load a DBC file first.")
            return

        # For each group, emit only ONE representative message (the first selected
        # member).  This is the whole point of grouping: 111 radar frames with
        # identical signal layouts produce ONE pack/unpack function set, not 111.
        # Ungrouped (single-message) entries behave exactly as before.
        representatives: List["cantools.database.can.Message"] = []
        for msgs in sorted(self._groups.values(), key=lambda v: min(m.frame_id for m in v)):
            rep = next((m for m in msgs if m.name in self._selected), None)
            if rep is not None:
                representatives.append(rep)

        if not representatives:
            messagebox.showwarning(
                "Nothing Selected",
                "Select at least one message to generate code for.",
            )
            return

        out_dir = self._out_path.get().strip()
        drv_name = self._drv_name.get().strip()
        sym_prefix = self._sym_prefix.get().strip()

        if not out_dir:
            messagebox.showwarning("Missing", "Please specify an output directory.")
            return
        if not drv_name:
            messagebox.showwarning("Missing", "Please specify a driver name.")
            return

        # Check for file conflicts on the main thread, before starting the worker.
        out = Path(out_dir)
        h_name = f"{drv_name}.h"
        c_name = f"{drv_name}.c"
        conflicts = [f for f in (h_name, c_name) if (out / f).exists()]
        if conflicts:
            names = "\n  • ".join(conflicts)
            if not messagebox.askyesno(
                "Files Already Exist",
                f"The following file(s) already exist in:\n{out_dir}\n\n  • {names}\n\nOverwrite?",
                parent=self,
            ):
                return

        self._gen_btn.configure(state="disabled")
        self._progress.configure(bootstyle="success-striped", mode="indeterminate")
        self._progress.start(10)
        threading.Thread(
            target=self._run_generation,
            args=(representatives, out_dir, drv_name, sym_prefix),
            daemon=True,
        ).start()

    def _run_generation(
        self,
        selected: List["cantools.database.can.Message"],
        out_dir: str,
        drv_name: str,
        sym_prefix: str,
    ) -> None:
        try:
            # Build a filtered in-memory database from the selected messages.
            filtered_db = cantools.database.Database(messages=selected)
            h_name = f"{drv_name}.h"
            c_name = f"{drv_name}.c"
            node = self._node_name.get().strip() or None

            self._log(
                f"Generating C code for {len(selected)} function set(s)…", tag="info"
            )

            header, source, _, _ = _ct_generate(
                filtered_db,
                drv_name,
                h_name,
                c_name,
                f"{drv_name}_fuzzer.c",
                floating_point_numbers=self._opt_fp.get(),
                bit_fields=self._opt_bitfields.get(),
                use_float=self._opt_use_float.get(),
                node_name=node,
                use_round=self._opt_use_round.get(),
            )

            # Post-process: replace identifier prefix if the user specified one
            # different from the driver name (or blank = strip entirely).
            if sym_prefix != drv_name:
                header, source = _replace_identifier_prefix(
                    header, source, drv_name, sym_prefix
                )

            # Post-process: strip disabled header sections
            if self._opt_skip_length.get():
                header = _strip_section(header, "Frame lengths in bytes.")
            if self._opt_skip_extended.get():
                header = _strip_section(header, "Extended or standard frame types.")
            if self._opt_skip_cycle_time.get():
                header = _strip_section(header, "Frame cycle times in milliseconds.")
            if self._opt_skip_frame_names.get():
                header = _strip_section(header, "Frame Names.")
            if self._opt_skip_sig_names.get():
                header = _strip_section(header, "Signal Names.")
            if self._opt_skip_validate.get():
                header = _strip_validate_funcs(header)
                source = _strip_validate_funcs(source)

            # Write output files (any conflict was already confirmed in _generate)
            out = Path(out_dir)
            out.mkdir(parents=True, exist_ok=True)

            for fname, content in [(h_name, header), (c_name, source)]:
                fpath = out / fname
                fpath.write_text(content, encoding="utf-8")
                self._log(f"  Written: {fpath}", tag="info")

            self._log(
                f"✅  Generation complete!  Output → {out_dir}", tag="success"
            )

        except Exception as exc:
            import traceback
            self._log(f"❌  {exc}", tag="danger")
            self._log(traceback.format_exc(), tag="danger")
        finally:
            self.after(0, self._generation_done)

    def _generation_done(self) -> None:
        self._progress.stop()
        self._progress.configure(bootstyle="secondary", mode="determinate")
        self._progress["value"] = 0
        self._gen_btn.configure(state="normal")

