    # ── Output filter master toggle ───────────────────────────────────────────

    def _on_filter_master_toggle(self) -> None:
        """Set all individual filter vars to match the master toggle."""
        state = self._opt_filter_master.get()
        for v in self._filter_vars:
            v.set(state)

    def _sync_filter_master(self) -> None:
        """Keep the master toggle in sync with the individual filter states."""
        all_on = all(v.get() for v in self._filter_vars)
        # Update without re-triggering traces that call back here.
        self._opt_filter_master.set(all_on)

    # ── DBC loading ──────────────────────────────────────────────────────────

    def _browse_dbc(self) -> None:
        saved = self._dbc_path.get()
        if saved and Path(saved).parent.is_dir():
            initial = str(Path(saved).parent)
        else:
            docs = Path.home() / "Documents"
            initial = str(docs) if docs.is_dir() else str(Path.home())
        path = filedialog.askopenfilename(
            title="Select DBC file",
            initialdir=initial,
            filetypes=[("DBC files", "*.dbc"), ("All files", "*.*")],
        )
        if path:
            self._dbc_path.set(path)
            self._load_dbc(path)

    def _load_dbc(self, path: str) -> None:
        self._log(f"Loading: {path}", tag="info")
        try:
            self._db = cantools.database.load_file(path)
        except Exception as exc:
            self._log(f"ERROR parsing DBC file: {exc}", tag="danger")
            return

        self._messages = sorted(self._db.messages, key=lambda m: m.frame_id)
        self._selected = {m.name for m in self._messages}

        # Start with a flat (one group per message) layout
        self._groups = {msg.name: [msg] for msg in self._messages}
        self._group_aliases.clear()
        self._frame_id_prefix_items.clear()
        self._populate_tree()
        self._update_summary()
        self._log(f"Loaded {len(self._messages)} message(s).", tag="success")

        # Auto-fill driver name and output dir from the filename
        stem = Path(path).stem
        if not self._drv_name.get():
            self._drv_name.set(stem)
        if not self._out_path.get():
            self._out_path.set(str(Path(path).parent / "gencode"))

    # ── Tree population ───────────────────────────────────────────────────────

    def _populate_tree(self) -> None:
        """Rebuild the entire Treeview from *self._groups*, respecting the search filter."""
        self._cancel_group_rename()
        self._tree.delete(*self._tree.get_children())
        self._tree_items.clear()

        filter_text = self._search_var.get().lower()

        for group_name, msgs in sorted(
            self._groups.items(), key=lambda kv: min(m.frame_id for m in kv[1])
        ):
            visible = [
                m for m in msgs
                if not filter_text or filter_text in m.name.lower()
            ]
            if not visible:
                continue

            is_group = len(msgs) > 1

            if is_group:
                all_sel = all(m.name in self._selected for m in visible)
                any_sel = any(m.name in self._selected for m in visible)
                chk = (
                    CHECKBOX_ON if all_sel
                    else CHECKBOX_PARTIAL if any_sel
                    else CHECKBOX_OFF
                )
                total_sigs = sum(len(m.signals) for m in visible)
                g_iid = f"group::{group_name}"
                fid_val = FID_ON if group_name in self._frame_id_prefix_items else FID_OFF
                self._tree.insert(
                    "", END, iid=g_iid,
                    values=(chk, fid_val, f"0x{min(m.frame_id for m in visible):03X}+",
                            self._group_name_cell_text(group_name, "▶", visible),
                            "", total_sigs, "✎ dbl-click to rename"),
                    open=False,
                    tags=("group",),
                )
                self._tree_items[g_iid] = ("group", group_name)
                for msg in visible:
                    self._insert_message(g_iid, msg)
            else:
                self._insert_message("", msgs[0])

        self._tree.tag_configure("group",  font=("", 11, "bold"))
        self._tree.tag_configure("signal", foreground="#888888")
        self._refresh_heading()

    def _insert_message(self, parent_iid: str, msg: "cantools.database.can.Message") -> None:
        selected = msg.name in self._selected
        chk = CHECKBOX_ON if selected else CHECKBOX_OFF
        m_iid = f"msg::{msg.frame_id}"
        sender = msg.senders[0] if msg.senders else ""
        has_sigs = bool(msg.signals)
        expand_indicator = "▶  " if has_sigs else "   "
        # fid column: only shown for top-level (non-grouped) message rows
        group_key = next(
            (k for k, v in self._groups.items() if any(m.name == msg.name for m in v)),
            msg.name,
        )
        fid_val = FID_ON if group_key in self._frame_id_prefix_items else FID_OFF
        # fid toggle is irrelevant for messages inside a group (group key controls it)
        fid_display = fid_val if not parent_iid else ""
        self._tree.insert(
            parent_iid, END, iid=m_iid,
            values=(chk, fid_display, f"{expand_indicator}0x{msg.frame_id:03X}", msg.name,
                    msg.length, len(msg.signals), sender),
            open=False,
            tags=("msg",),
        )
        self._tree_items[m_iid] = ("msg", msg)

        for sig in msg.signals:
            s_iid = f"sig::{msg.frame_id}::{sig.name}"
            bo = "LE" if sig.byte_order == "little_endian" else "BE"
            vt = "S" if sig.is_signed else "U"
            self._tree.insert(
                m_iid, END, iid=s_iid,
                values=("", "", "", f"    {sig.name}  [{sig.start}|{sig.length}]", bo, vt, ""),
                tags=("signal",),
            )

    # ── Tree interaction ──────────────────────────────────────────────────────

    def _on_tree_click(self, event: "tk.Event[ttk.Treeview]") -> None:
        """Handle clicks in the sel, fid, and name columns."""
        if self._tree.identify_region(event.x, event.y) != "cell":
            return

        iid = self._tree.identify_row(event.y)
        if not iid or iid not in self._tree_items:
            return

        col = self._tree.identify_column(event.x)
        # col numbers: #1=sel, #2=fid, #3=id, #4=name, #5=dlc, #6=signals, #7=transmitter

        kind, data = self._tree_items[iid]

        if col == "#2":
            # fid column: toggle frame-ID prefix for this group/message
            if kind == "signal":
                return
            if kind == "group":
                self._toggle_frame_id_prefix(str(data))
            elif kind == "msg":
                msg = data  # type: ignore[assignment]
                group_key = next(
                    (k for k, v in self._groups.items() if any(m.name == msg.name for m in v)),  # type: ignore[union-attr]
                    msg.name,  # type: ignore[union-attr]
                )
                self._toggle_frame_id_prefix(group_key)
            return

        if col not in ("#1", "#4"):
            return

        if kind == "group":
            if col == "#4":
                # Name column click → expand/collapse the group
                self._toggle_group_expand(str(data))
                return
            # Sel column click → toggle selection of all messages in group
            self._toggle_group(str(data))
        elif kind == "msg":
            msg = data  # type: ignore[assignment]
            if col == "#4" and msg.signals:  # type: ignore[union-attr]
                self._toggle_msg_expand(msg)  # type: ignore[arg-type]
                return
            self._toggle_message(data)  # type: ignore[arg-type]

        self._update_summary()

    def _on_tree_double_click(self, event: "tk.Event[ttk.Treeview]") -> None:
        """Start an inline rename when the user double-clicks a group row's name cell."""
        if self._tree.identify_region(event.x, event.y) != "cell":
            return
        iid = self._tree.identify_row(event.y)
        if not iid or iid not in self._tree_items:
            return
        col = self._tree.identify_column(event.x)
        if col != "#4":
            return
        kind, data = self._tree_items[iid]
        if kind != "group":
            return
        self._start_group_rename(str(data))

    def _toggle_frame_id_prefix(self, group_key: str) -> None:
        """Enable or disable the frame-ID identifier prefix for *group_key*."""
        if group_key in self._frame_id_prefix_items:
            self._frame_id_prefix_items.discard(group_key)
        else:
            self._frame_id_prefix_items.add(group_key)
        fid_val = FID_ON if group_key in self._frame_id_prefix_items else FID_OFF
        # Refresh the fid column on the affected row.
        g_iid = f"group::{group_key}"
        if self._tree.exists(g_iid):
            self._tree.set(g_iid, "fid", fid_val)
        else:
            # Single-message top-level row
            msgs = self._groups.get(group_key, [])
            if msgs:
                m_iid = f"msg::{msgs[0].frame_id}"
                if self._tree.exists(m_iid):
                    self._tree.set(m_iid, "fid", fid_val)

    def _start_group_rename(self, group_key: str) -> None:
        """Overlay an Entry widget on the group row's name cell for inline editing."""
        self._cancel_group_rename()  # cancel any previous rename in progress

        g_iid = f"group::{group_key}"
        bbox = self._tree.bbox(g_iid, "name")
        if not bbox:
            return  # row not visible
        x, y, width, height = bbox

        current_name = self._group_aliases.get(group_key, group_key)
        var = tk.StringVar(value=current_name)
        entry = ttk.Entry(self._tree, textvariable=var, font=("", 11, "bold"))
        entry.place(x=x, y=y, width=width, height=height)
        entry.focus_set()
        entry.select_range(0, tk.END)

        self._rename_entry = entry
        self._rename_group_key = group_key

        entry.bind("<Return>", lambda _e: self._confirm_group_rename())
        entry.bind("<KP_Enter>", lambda _e: self._confirm_group_rename())
        entry.bind("<Escape>", lambda _e: self._cancel_group_rename())
        entry.bind("<FocusOut>", lambda _e: self._confirm_group_rename())

    def _confirm_group_rename(self) -> None:
        """Validate and apply the rename, then remove the entry widget."""
        entry = self._rename_entry
        group_key = self._rename_group_key
        if entry is None or group_key is None:
            return

        new_name = entry.get().strip()
        self._cancel_group_rename()  # destroy entry before any messagebox

        if not new_name:
            return  # empty name → silently cancel

        # Check uniqueness: no other group may already display the same name
        existing_names = {
            self._group_aliases.get(k, k)
            for k in self._groups
            if k != group_key
        }
        if new_name in existing_names:
            messagebox.showwarning(
                "Name Already Used",
                f'A group named "{new_name}" already exists.\nPlease choose a different name.',
                parent=self,
            )
            return

        self._group_aliases[group_key] = new_name

        # Update the treeview row text in-place (no full repopulate needed)
        g_iid = f"group::{group_key}"
        if self._tree.exists(g_iid):
            msgs = self._groups[group_key]
            is_open = bool(self._tree.item(g_iid, "open"))
            indicator = "▼" if is_open else "▶"
            self._tree.set(g_iid, "name", self._group_name_cell_text(group_key, indicator, msgs))

    def _cancel_group_rename(self) -> None:
        """Discard the inline rename and remove the Entry widget."""
        if self._rename_entry is not None:
            try:
                self._rename_entry.destroy()
            except tk.TclError:
                pass
            self._rename_entry = None
            self._rename_group_key = None

    def _group_name_cell_text(self, group_key: str, indicator: str, msgs: list) -> str:
        """Return the formatted text for a group row's name cell."""
        display_name = self._group_aliases.get(group_key, group_key)
        return f"{indicator}  {display_name}  ({len(msgs)} frames → 1 function set)"

    def _toggle_group_expand(self, group_name: str) -> None:
        """Flip the open/close state of a group row and update its ▶/▼ indicator."""
        g_iid = f"group::{group_name}"
        if not self._tree.exists(g_iid):
            return
        msgs = self._groups[group_name]
        is_open = bool(self._tree.item(g_iid, "open"))
        self._tree.item(g_iid, open=not is_open)
        indicator = "▼" if not is_open else "▶"
        self._tree.set(g_iid, "name", self._group_name_cell_text(group_name, indicator, msgs))

    def _toggle_msg_expand(self, msg: "cantools.database.can.Message") -> None:
        """Flip the open/close state of a message row and update its ▶/▼ indicator."""
        m_iid = f"msg::{msg.frame_id}"
        if not self._tree.exists(m_iid):
            return
        is_open = bool(self._tree.item(m_iid, "open"))
        self._tree.item(m_iid, open=not is_open)
        indicator = "▼  " if not is_open else "▶  "
        self._tree.set(m_iid, "id", f"{indicator}0x{msg.frame_id:03X}")

    def _toggle_message(self, msg: "cantools.database.can.Message") -> None:
        if msg.name in self._selected:
            self._selected.discard(msg.name)
        else:
            self._selected.add(msg.name)
        selected = msg.name in self._selected
        chk = CHECKBOX_ON if selected else CHECKBOX_OFF
        m_iid = f"msg::{msg.frame_id}"
        if self._tree.exists(m_iid):
            self._tree.set(m_iid, "sel", chk)
        self._refresh_parent_group(msg)
        self._refresh_heading()

    def _toggle_group(self, group_name: str) -> None:
        msgs = self._groups[group_name]
        all_sel = all(m.name in self._selected for m in msgs)
        if all_sel:
            for msg in msgs:
                self._selected.discard(msg.name)
        else:
            for msg in msgs:
                self._selected.add(msg.name)
        for msg in msgs:
            chk = CHECKBOX_ON if msg.name in self._selected else CHECKBOX_OFF
            m_iid = f"msg::{msg.frame_id}"
            if self._tree.exists(m_iid):
                self._tree.set(m_iid, "sel", chk)
        self._refresh_group_item(group_name)
        self._refresh_heading()

    def _refresh_group_item(self, group_name: str) -> None:
        g_iid = f"group::{group_name}"
        if not self._tree.exists(g_iid):
            return
        msgs = self._groups[group_name]
        all_sel = all(m.name in self._selected for m in msgs)
        any_sel = any(m.name in self._selected for m in msgs)
        chk = (
            CHECKBOX_ON if all_sel
            else CHECKBOX_PARTIAL if any_sel
            else CHECKBOX_OFF
        )
        n = len(msgs)
        min_id = min(m.frame_id for m in msgs)
        self._tree.set(g_iid, "sel", chk)

    def _refresh_parent_group(self, msg: "cantools.database.can.Message") -> None:
        for group_name, msgs in self._groups.items():
            if msg in msgs and len(msgs) > 1:
                self._refresh_group_item(group_name)
                break

    # ── Grouping ──────────────────────────────────────────────────────────────

    def _auto_group(self) -> None:
        if not self._messages:
            return
        self._groups = detect_groups(self._messages)
        self._group_aliases.clear()
        self._populate_tree()
        n_groups = sum(1 for v in self._groups.values() if len(v) > 1)
        self._log(
            f"Auto-grouping complete: {n_groups} group(s) detected.", tag="info"
        )

    def _ungroup(self) -> None:
        if not self._messages:
            return
        self._groups = {msg.name: [msg] for msg in self._messages}
        self._group_aliases.clear()
        self._populate_tree()

    # ── Selection helpers ─────────────────────────────────────────────────────

    def _select_all(self) -> None:
        self._selected = {m.name for m in self._messages}
        self._populate_tree()
        self._update_summary()

    def _deselect_all(self) -> None:
        self._selected.clear()
        self._populate_tree()
        self._update_summary()

    def _toggle_all_heading(self) -> None:
        """Toggle all messages on/off when the sel column heading checkbox is clicked."""
        if not self._messages:
            return
        all_sel = all(m.name in self._selected for m in self._messages)
        if all_sel:
            self._selected.clear()
        else:
            self._selected = {m.name for m in self._messages}
        self._populate_tree()
        self._update_summary()

    def _refresh_heading(self) -> None:
        """Update the sel column heading checkbox to reflect the current selection state."""
        if not self._messages:
            chk = CHECKBOX_OFF
        elif all(m.name in self._selected for m in self._messages):
            chk = CHECKBOX_ON
        elif any(m.name in self._selected for m in self._messages):
            chk = CHECKBOX_PARTIAL
        else:
            chk = CHECKBOX_OFF
        self._tree.heading("sel", text=chk)

    def _apply_filter(self) -> None:
        self._populate_tree()

    def _update_summary(self) -> None:
        total = len(self._messages)
        sel = sum(1 for m in self._messages if m.name in self._selected)
        func_sets = sum(
            1 for msgs in self._groups.values()
            if any(m.name in self._selected for m in msgs)
        )
        self._summary_var.set(f"{total} messages  |  {sel} selected")
        self._sel_summary.set(
            f"{sel} / {total} messages selected  →  {func_sets} function set(s) will be generated"
        )

    # ── Code generation ───────────────────────────────────────────────────────

    def _generate(self) -> None:
        if not self._messages:
            messagebox.showwarning("No DBC", "Please load a DBC file first.")
            return

        # For each group, emit only ONE representative message (the first selected
        # member).  This is the whole point of grouping: 111 radar frames with
        # identical signal layouts produce ONE pack/unpack function set, not 111.
        # Ungrouped (single-message) entries behave exactly as before.
        representatives: List["cantools.database.can.Message"] = []
        for msgs in sorted(self._groups.values(), key=lambda v: min(m.frame_id for m in v)):
            rep = next((m for m in msgs if m.name in self._selected), None)
            if rep is not None:
                representatives.append(rep)

        if not representatives:
            messagebox.showwarning(
                "Nothing Selected",
                "Select at least one message to generate code for.",
            )
            return

        out_dir = self._out_path.get().strip()
        drv_name = self._drv_name.get().strip()
        sym_prefix = self._sym_prefix.get().strip()

        if not out_dir:
            messagebox.showwarning("Missing", "Please specify an output directory.")
            return
        if not drv_name:
            messagebox.showwarning("Missing", "Please specify a driver name.")
            return

        # Check for file conflicts on the main thread, before starting the worker.
        out = Path(out_dir)
        h_name = f"{drv_name}.h"
        c_name = f"{drv_name}.c"
        conflicts = [f for f in (h_name, c_name) if (out / f).exists()]
        if conflicts:
            names = "\n  • ".join(conflicts)
            if not messagebox.askyesno(
                "Files Already Exist",
                f"The following file(s) already exist in:\n{out_dir}\n\n  • {names}\n\nOverwrite?",
                parent=self,
            ):
                return

        self._gen_btn.configure(state="disabled")
        self._progress.configure(bootstyle="success-striped", mode="indeterminate")
        self._progress.start(10)
        # Snapshot mutable state so the worker thread sees a consistent view.
        groups_snapshot = {k: list(v) for k, v in self._groups.items()}
        selected_snapshot = set(self._selected)
        frame_id_prefix_snapshot = set(self._frame_id_prefix_items)
        threading.Thread(
            target=self._run_generation,
            args=(representatives, out_dir, drv_name, sym_prefix,
                  groups_snapshot, selected_snapshot, frame_id_prefix_snapshot),
            daemon=True,
        ).start()

    def _run_generation(
        self,
        selected: List["cantools.database.can.Message"],
        out_dir: str,
        drv_name: str,
        sym_prefix: str,
        groups: Dict[str, List["cantools.database.can.Message"]],
        selected_names: Set[str],
        frame_id_prefix_items: Set[str],
    ) -> None:
        try:
            # Build a filtered in-memory database from the selected messages.
            filtered_db = cantools.database.Database(messages=selected)
            h_name = f"{drv_name}.h"
            c_name = f"{drv_name}.c"
            node = self._node_name.get().strip() or None

            self._log(
                f"Generating C code for {len(selected)} function set(s)…", tag="info"
            )

            header, source, _, _ = _ct_generate(
                filtered_db,
                drv_name,
                h_name,
                c_name,
                f"{drv_name}_fuzzer.c",
                floating_point_numbers=self._opt_fp.get(),
                bit_fields=self._opt_bitfields.get(),
                use_float=self._opt_use_float.get(),
                node_name=node,
                use_round=self._opt_use_round.get(),
            )

            # Post-process: always strip the cantools database/driver name prefix
            # so the message/frame name becomes the outermost identifier namespace.
            # e.g. ars_radar_ars_obj_00_dist_x_encode → ars_obj_00_dist_x_encode
            header, source = _replace_identifier_prefix(
                header, source, drv_name, ""
            )

            # Post-process: for grouped messages replace the representative
            # message's name segment with the group key so identifiers use the
            # common prefix rather than the specific instance.
            # e.g. ars_obj_00_dist_x_encode → ars_obj_dist_x_encode
            header, source = _rename_grouped_message_prefix(
                header, source, groups, selected_names
            )

            # Post-process: replace the group/message name prefix with the hex
            # frame-ID for entries that have the frame-ID prefix option enabled.
            # e.g. ars_obj_dist_x_encode → x400_dist_x_encode  (frame ID 0x400)
            if frame_id_prefix_items:
                header, source = _apply_frame_id_prefix(
                    header, source, groups, selected_names, frame_id_prefix_items
                )

            # Post-process: strip redundant signal suffix for grouped messages
            # (e.g. every signal in ARS_Obj_00 ends with _Obj_00 → strip it so
            # ars_obj_dist_x_obj_00_encode becomes ars_obj_dist_x_encode).
            if self._opt_strip_sig_suffix.get():
                header, source = _strip_redundant_signal_suffixes(
                    header, source, groups, selected_names
                )

            # Post-process: strip message/group name prefix from signal identifiers
            # (e.g. ars_obj_status_vehicle_platform_sig_decode → vehicle_platform_sig_decode).
            # Groups/messages with a hex frame-ID prefix are left untouched.
            if self._opt_strip_msg_name_prefix.get():
                header, source = _strip_message_name_prefix(
                    header, source, groups, selected_names, frame_id_prefix_items
                )

            # Post-process: inject frame-ID macros for all selected grouped messages
            # before any section-strip passes (strips will then apply uniformly).
            if self._opt_expand_group_ids.get():
                header = _inject_group_frame_ids(
                    header, groups, selected_names, ""
                )

            # Post-process: inject FRAME_ID_FIRST / FRAME_ID_LAST / FRAME_ID_COUNT
            # range macros for every group (always emitted when groups are present).
            header = _inject_group_range_macros(header, groups, selected_names)

            # Post-process: strip disabled header sections
            if self._opt_skip_length.get():
                header = _strip_section(header, "Frame lengths in bytes.")
            if self._opt_skip_extended.get():
                header = _strip_section(header, "Extended or standard frame types.")
            if self._opt_skip_cycle_time.get():
                header = _strip_section(header, "Frame cycle times in milliseconds.")
            if self._opt_skip_frame_names.get():
                header = _strip_section(header, "Frame Names.")
            if self._opt_skip_sig_names.get():
                header = _strip_section(header, "Signal Names.")
            if self._opt_skip_choices.get():
                header = _strip_section(header, "Signal choices.")
            if self._opt_skip_validate.get():
                header = _strip_validate_funcs(header)
                source = _strip_validate_funcs(source)

            # Post-process: replace inline bitshift helpers with a user include.
            bitshift_hdr = self._bitshift_header.get().strip()
            if bitshift_hdr:
                source = _replace_bitshift_funcs(source, bitshift_hdr)

            # Write output files (any conflict was already confirmed in _generate)
            out = Path(out_dir)
            out.mkdir(parents=True, exist_ok=True)

            for fname, content in [(h_name, header), (c_name, source)]:
                fpath = out / fname
                fpath.write_text(content, encoding="utf-8")
                self._log(f"  Written: {fpath}", tag="info")

            self._log(
                f"✅  Generation complete!  Output → {out_dir}", tag="success"
            )

        except Exception as exc:
            import traceback
            self._log(f"❌  {exc}", tag="danger")
            self._log(traceback.format_exc(), tag="danger")
        finally:
            self.after(0, self._generation_done)

    def _generation_done(self) -> None:
        self._progress.stop()
        self._progress.configure(bootstyle="secondary", mode="determinate")
        self._progress["value"] = 0
        self._gen_btn.configure(state="normal")

